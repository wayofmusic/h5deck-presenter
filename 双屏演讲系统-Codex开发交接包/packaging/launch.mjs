import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { spawn, spawnSync } from 'node:child_process';
const root = fileURLToPath(new URL('../',import.meta.url));
const runtime = path.join(root,'.runtime'); fs.mkdirSync(runtime,{recursive:true});
const recordFile = path.join(runtime,'server.json');
const instanceId = crypto.createHash('sha256').update(root).digest('hex').slice(0,16);
const version=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8')).version;
async function existing() {
  try {
    const record = JSON.parse(fs.readFileSync(recordFile));
    const health = await (await fetch(`http://localhost:${record.port}/api/health`,{signal:AbortSignal.timeout(1000)})).json();
    if (health.instanceId === instanceId) return {...record,runningVersion:health.version};
  } catch {}
  return null;
}
let record = await existing();
if (process.argv.includes('--stop')) {
  if (record) { process.kill(record.pid,'SIGTERM'); console.log('双屏演讲服务已停止。'); }
  else console.log('没有正在运行的本项目服务。');
  process.exit(0);
}
if(record&&record.runningVersion!==version) {
  console.log(`检测到本项目旧版本 ${record.runningVersion}，正在切换到 ${version}。`);
  process.kill(record.pid,'SIGTERM');record=null;
}
if (!record) {
  if (!fs.existsSync(path.join(root,'dist/content-packs/basic.h5deck')) || (!fs.existsSync(path.join(root,'dist/chaixiang-ai-y/display.html'))&&fs.existsSync(path.join(root,'baseline/work/content.js')))) {
    const build = spawnSync(process.execPath,[path.join(root,'packaging/build.mjs')],{cwd:root,stdio:'inherit',windowsHide:true});
    if (build.status !== 0) throw Error('课件构建失败');
  }
  const log = fs.openSync(path.join(runtime,'server.log'),'a');
  const child = spawn(process.execPath,[path.join(root,'server/index.mjs')],{cwd:root,detached:true,windowsHide:true,stdio:['ignore',log,log]});
  child.unref(); fs.closeSync(log);
  for (let n=0;n<40;n++) { await new Promise(resolve=>setTimeout(resolve,150)); record=await existing(); if(record) break; }
  if (!record) throw Error('服务启动失败，请查看 .runtime/server.log');
}
console.log(`双屏演讲已就绪：${record.url}`);
if (!process.argv.includes('--no-open')) {
  // The URL is generated by this local server, never supplied by a remote page.
  const opener = spawn('cmd.exe',['/d','/s','/c',`start "" "http://localhost:${record.port}/host"`],{windowsHide:true,stdio:'ignore'});
  opener.unref();
}
